import type { EntryId } from '../../entries/index.ts';
import type { BedReport, ReportProvenance, SensitivityPoint, SplitReport } from '../model.ts';
import { provenanceLine } from './provenance-line.ts';
import { catchLine, countCell, rateLine } from './rate-text.ts';

const crossFaultLines = (split: SplitReport, entryId: EntryId): readonly string[] =>
    split.confusion.flatMap((row) => {
        const fired = row.firedByEntry.find((cell) => cell.entryId === entryId)?.fired;
        return row.ownEntryId !== null && row.ownEntryId !== entryId && fired !== undefined && fired.events > 0
            ? [`  - ${row.condition}: fired ${countCell(fired)}`]
            : [];
    });

const sweepPointText = (point: SensitivityPoint): string =>
    `${point.value}${point.isDefault ? ' (default)' : ''}: caught ${countCell(point.caught)}, ` +
    `false alarms ${countCell(point.falseAlarms)}`;

/** One line per swept threshold: what each value would have caught and fired on clean runs, on this split. */
const sensitivityLines = (split: SplitReport, entryId: EntryId): readonly string[] => {
    const sweeps = split.sensitivity.filter((sweep) => sweep.entryId === entryId);
    return sweeps.length === 0
        ? []
        : [
              '- Threshold sensitivity (one threshold at a time, the others at their defaults; caught over expressed runs):',
              ...sweeps.map((sweep) => `  - \`${sweep.threshold}\`: ${sweep.points.map(sweepPointText).join('; ')}`),
          ];
};

const detectorLines = (split: SplitReport, entryId: EntryId): readonly string[] => {
    const detector = split.detectors.find((candidate) => candidate.entryId === entryId);
    if (detector === undefined) {
        return ['No held-out runs scored this entry.'];
    }
    const crossFault = crossFaultLines(split, entryId);
    return [
        `- ${catchLine(detector)}`,
        ...detector.caughtBySeverity.map(
            (severity) => `  - ${severity.faultId} / ${severity.severity}: ${catchLine(severity)}`,
        ),
        `- ${rateLine('false alarms', detector.falseAlarms)}`,
        ...detector.falseAlarmsByVariation
            .filter((variation) => variation.hardNegative)
            .map(
                (variation) =>
                    `  - hard negative ${variation.variation}: ${rateLine('false alarms', variation.falseAlarms)}`,
            ),
        crossFault.length === 0 ? "- Fires on no other entry's fault." : "- Also fires on other entries' faults:",
        ...crossFault,
        ...sensitivityLines(split, entryId),
    ];
};

/**
 * The text between an entry page's results markers: held-out numbers only, with their source and platform. Scripted
 * faults are caught partly by construction, and the block says so next to the numbers.
 */
export const entryResultsBlock = (report: BedReport, entryId: EntryId, provenance: ReportProvenance): string => {
    const heldOut = report.splits.find((split) => split.split === 'held-out');
    return [
        provenanceLine(provenance),
        '',
        ...(heldOut === undefined ? ['No held-out runs.'] : detectorLines(heldOut, entryId)),
        '',
        'Held-out families vary retrieval config, query phrasing, answer and abstention wording, and supervisor and ' +
            'worker wording, and the clean pool holds hard negatives; the faults themselves are our reproductions, so ' +
            'a high catch rate shows the detector matches them, not how often the failure occurs or is caught in the ' +
            'wild. Generated by `pnpm docs:tables` from `results/offline/report.json`.',
    ].join('\n');
};
